def _tool_call_line(tool: str, tool_input: dict) -> str:
    import json

    block = {"type": "tool_use", "id": "t1", "name": tool, "input": tool_input}
    return json.dumps({"type": "assistant", "message": {"role": "assistant", "content": [block]}})


